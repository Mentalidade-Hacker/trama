"""Build the offline Windows installer from verified, already downloaded tools.

No download, installation or user-data access is performed by this builder.
The runtime input is the tools/ directory of the official x64 CPython NuGet
package. Inno Setup and the Windows .NET Framework C# compiler are build tools.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile

from updater import hash_file, plain_path, read_json, validate_manifest, version_key


REQUIRED_APP = {
    'server.py', 'launch_trama.py', 'updater.py', 'learning_drafts.py',
    'full_backup.py', 'setup_proofreader.py', 'setup_translation.py',
    'web/index.html', 'web/app.js',
}
REQUIRED_RUNTIME = {
    'python.exe', 'pythonw.exe', 'LICENSE.txt', 'vcruntime140.dll',
    'Lib/encodings/__init__.py', 'Lib/venv/__init__.py',
    'Lib/ensurepip/__init__.py', 'DLLs/_sqlite3.pyd', 'DLLs/_ssl.pyd',
}


def regular(path):
    path = plain_path(Path(path))
    if not path.is_file():
        raise ValueError('Arquivo obrigatório ausente: ' + str(path))
    return path


def probe_runtime(runtime, runner=subprocess.run):
    """Run only the supplied local Python, isolated from PATH/site packages."""
    runtime = plain_path(Path(runtime).absolute())
    for name in REQUIRED_RUNTIME:
        regular(runtime / name)
    code = ('import json,sys,struct,ssl,sqlite3,venv,ensurepip;'
            'print(json.dumps({"version":".".join(map(str,sys.version_info[:3])), '
            '"bits":struct.calcsize("P")*8,"platform":sys.platform}))')
    result = runner([str(runtime / 'python.exe'), '-I', '-B', '-c', code],
                    check=True, capture_output=True, text=True, timeout=60)
    details = json.loads(result.stdout)
    if (details.get('bits') != 64 or details.get('platform') != 'win32'
            or version_key(details.get('version')) < (3, 10, 0)):
        raise ValueError('É necessário CPython Windows x64 3.10 ou superior.')
    return details


def runtime_files(runtime):
    """Ignore generated bytecode; refuse links, hidden state and special files."""
    runtime = plain_path(Path(runtime).absolute())
    for current, directories, filenames in os.walk(runtime, topdown=True, followlinks=False):
        directories[:] = sorted(name for name in directories if name != '__pycache__')
        for name in directories:
            path = plain_path(Path(current) / name)
            if name.startswith('.'):
                raise ValueError('Estado oculto inesperado no runtime: ' + str(path.relative_to(runtime)))
        for name in sorted(filenames):
            path = Path(current) / name
            if path.suffix.lower() in {'.pyc', '.pyo'}:
                continue
            plain_path(path)
            relative = path.relative_to(runtime)
            if name.startswith('.'):
                raise ValueError('Estado oculto inesperado no runtime: ' + str(relative))
            if not path.is_file():
                raise ValueError('Arquivo especial inesperado no runtime: ' + str(relative))
            yield path, relative


def prepare_payload(source, runtime, destination, version, runtime_details,
                    runtime_package_sha256=None):
    """Stage only manifest files, the public dictionary and the supplied runtime."""
    source = plain_path(Path(source).absolute())
    runtime = plain_path(Path(runtime).absolute())
    destination = plain_path(Path(destination).absolute())
    if destination.exists():
        raise ValueError('A pasta temporária do pacote precisa ser nova.')
    if destination.is_relative_to(source) or destination.is_relative_to(runtime):
        raise ValueError('A pasta temporária não pode ficar dentro da origem.')
    manifest = validate_manifest(read_json(source / 'app-release.json'), version)
    if not REQUIRED_APP <= manifest['files'].keys():
        raise ValueError('O manifesto omitiu módulos necessários à instalação completa.')
    dictionary = regular(source / 'resources/dictionary.sqlite')
    with dictionary.open('rb') as stream:
        if stream.read(16) != b'SQLite format 3\0':
            raise ValueError('O dicionário offline não é um banco SQLite válido.')
    if runtime_package_sha256 is not None and not re.fullmatch(r'[0-9a-f]{64}', runtime_package_sha256):
        raise ValueError('SHA-256 do pacote Python inválido.')
    for name in REQUIRED_RUNTIME:
        regular(runtime / name)
    files = list(runtime_files(runtime))
    destination.mkdir(parents=True)
    app = destination / 'app'
    app.mkdir()
    for name, expected in manifest['files'].items():
        src = regular(source / name)
        target = app / name
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, target)
        if target.stat().st_size != expected['size'] or hash_file(target) != expected['sha256']:
            raise ValueError('A origem diverge do manifesto: ' + name)
    (app / 'app-release.json').write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    (app / 'resources').mkdir(exist_ok=True)
    shutil.copy2(dictionary, app / 'resources/dictionary.sqlite')
    for src, relative in files:
        target = destination / 'runtime' / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, target)
    provenance = {
        'runtime': 'CPython x64 NuGet', 'version': runtime_details['version'],
        'source': f'https://www.nuget.org/packages/python/{runtime_details["version"]}',
        'packageSha256': runtime_package_sha256, 'license': 'runtime/LICENSE.txt',
        'updates': 'O atualizador do Trama atualiza somente app/, não este runtime.',
    }
    (destination / 'runtime-source.json').write_text(json.dumps(provenance, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    return {'appFiles': len(manifest['files']) + 2, 'runtimeFiles': len(files),
            'runtime': runtime_details, 'dictionaryBytes': dictionary.stat().st_size}


def write_inventory(stage):
    """Allow exact installed paths, including directories, for destination checks."""
    names = sorted({path.relative_to(stage).as_posix().lower() + ('/' if path.is_dir() else '')
                    for path in stage.rglob('*')})
    target = stage / 'install-files.txt'
    target.write_text('\n'.join(names) + '\n', encoding='utf-8')
    return target


def build(source, runtime, iscc, csc, output, version='0.10.2', work=None,
          runtime_package_sha256=None, runner=subprocess.run):
    version_key(version)
    source = plain_path(Path(source).absolute())
    runtime = plain_path(Path(runtime).absolute())
    output = plain_path(Path(output).absolute())
    for root in (source, runtime):
        if output.is_relative_to(root):
            raise ValueError('A saída precisa ficar fora das pastas de origem.')
    iscc, csc = regular(iscc), regular(csc)
    script = regular(source / 'windows/trama.iss')
    launcher = regular(source / 'windows/TramaLauncher.cs')
    details = probe_runtime(runtime, runner)
    if work is not None:
        work = plain_path(Path(work).absolute())
        work.mkdir(parents=True, exist_ok=True)
    # Every destructive cleanup is confined to this newly created directory.
    with tempfile.TemporaryDirectory(prefix='trama-windows-', dir=work) as temp:
        temporary = Path(temp)
        stage = temporary / 'payload'
        metadata = prepare_payload(source, runtime, stage, version, details, runtime_package_sha256)
        runner([str(csc), '/nologo', '/target:winexe', '/platform:x64', '/optimize+',
                '/reference:System.Windows.Forms.dll', '/reference:System.Drawing.dll',
                '/reference:System.Web.Extensions.dll', '/out:' + str(stage / 'Trama.exe'),
                str(launcher)], check=True, timeout=120)
        regular(stage / 'Trama.exe')
        write_inventory(stage)
        compiled = temporary / 'compiled'
        compiled.mkdir()
        runner([str(iscc), '/DStageDir=' + str(stage), '/DOutputDir=' + str(compiled),
                '/DAppVersion=' + version, str(script)], check=True, timeout=1800)
        name = f'trama-v{version}-windows-setup.exe'
        built = regular(compiled / name)
        with built.open('rb') as stream:
            if stream.read(2) != b'MZ':
                raise ValueError('O compilador não produziu um instalador Windows válido.')
        output.mkdir(parents=True, exist_ok=True)
        final = output / name
        # Old release output is replaced only after both compilers succeeded.
        os.replace(built, final)
    return dict(metadata, version=version, file=str(final), bytes=final.stat().st_size,
                sha256=hash_file(final))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=Path(__file__).resolve().parent)
    parser.add_argument('--runtime', type=Path, required=True, help='tools/ do NuGet CPython x64 já extraído')
    parser.add_argument('--iscc', type=Path, required=True)
    parser.add_argument('--csc', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--work', type=Path)
    parser.add_argument('--version', default='0.10.2')
    parser.add_argument('--runtime-package-sha256')
    args = parser.parse_args()
    print(json.dumps(build(**vars(args)), ensure_ascii=False))


if __name__ == '__main__':
    main()
